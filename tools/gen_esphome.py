ROOT = Path(__file__).resolve().parent.parent
# Source and outputs both follow build_paths.py: a sandboxed studio (its own
# CASTLE_SCENES) generates under its own build root, never the repo's.
SRC = bp.SCENES
MARKERS = bp.AUDIO / "markers.json"
OUT = bp.GENERATED / "scenes.yaml"
RIG_OUT = bp.GENERATED / "rig.h"
# The strips, written ONCE and read by both builds. There was a second,
# generated `lights_s3.yaml` beside this — a package of `!extend`s that
# re-spent every strip's RMT block in the S3's 48-word units, because the
# strips here were written for the S2's 64. The S2 was retired on 2026-09-17
# and these are native S3 now, so the override had nothing left to say and is
# gone; the only RMT difference between the two builds is whether a status
# pixel holds the fourth channel, which is a RESERVATION and not a number in
# this file (gen_rig.STATUS_PIXEL_BLOCKS, and the banner that names both).
LIGHTS_OUT = bp.GENERATED / "lights.yaml"
AUDIO_SD = bp.GENERATED / "audio_sd.yaml"
FALLBACK_SCENES_OUT = bp.GENERATED / "fallback_scenes.h"
# The show itself, for `sd_sync scenes` to push into the card's scenes/
# directory beside the audio it already pushes there.
CARD_SCENES = bp.AUDIO / "card" / "scenes"

#: The two lines of ESPHome boilerplate the entity blocks below repeat — five
#: platform headers and three optimistic flags. Named because they are one
#: fact about how these entities are declared, and a typo in one copy is an
#: entity the build quietly drops rather than an error anyone sees.
PLATFORM_TEMPLATE = "  - platform: template"
OPTIMISTIC = "    optimistic: true"

HEADER = """# GENERATED BY tools/gen_esphome.py — DO NOT EDIT
#
# Source of truth: scenes/scenes.yaml
# Regenerate with:  make generate
#
# The show as a WHOLE: blackout, dispatch by name, the evening playlist. What
# one scene DOES is not here — it is a cue file on the card since v5.67
# (audio/card/scenes/<id>.cue, firmware/castle_scenes.h).
"""

# The effect/overlay/palette/flash-mask names and their firmware ids live in
# tools/effect_vocab.py — one table for both generators, the schema and the
# parity test. Re-exported here so `ge.EFFECT_IDS` keeps working.
# (plus the pulse contract: gen_previewer, fuzz_check and the parity tests
# read DEFAULT_DECAY/WHITE/pulse_cues/round3/section_gates/thin_pulses
