#!/usr/bin/env python3
"""Generate the firmware's share of the show from scenes.yaml.

Hand-writing any of this would mean the cue timings in the previewer and the
cue timings on the device drift apart within a week. They come from one file
instead.

    tools/gen_esphome.py        # writes firmware/generated/ + audio/card/scenes/

What it writes, and why each is here rather than on the card:

    generated/scenes.yaml    the three scripts that are about the show as a
                             WHOLE — blackout, dispatch-by-name, the evening
                             playlist — plus the show-state sensors and the
                             PIR's entities (whose scene is a free text field
                             since v5.69 — the card validates it, not the
                             compiled options)
    generated/audio_sd.yaml  `sfx`: stream a scene's track off the card
    generated/rig.h          the pixel counts, RMT budget and volume ceiling
    generated/lights.yaml    a strip per zone
    generated/fallback_scenes.h  what the firmware knows with NO card
    audio/card/scenes/       show.man + one <id>.cue per scene — the show
                             itself, for `sd_sync scenes` to publish

Until v5.67 each scene was also an ESPHome script: publish current_scene, a
lambda of base-state assignments, `sfx`, and then a `delay:` and a lambda per
cue, chopped into `cont_<id>_N` continuations. Twelve of them measured 744
LambdaActions, 573 DelayActions and 85 ScriptExecuteActions — ~23 KB of static
internal RAM and 744 compiled lambdas, in the resource that actually binds
this board. They are a card file now (tools/gen_scene_cards.py, walked by
firmware/castle_scenes.h), so a scene edit is a publish and not an OTA.
"""

